-- NOVARA database schema for Supabase. Run this in Supabase SQL Editor.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('T-Shirts','Pants')),
  price integer not null check (price >= 0),
  old_price integer not null default 0,
  tag text not null default 'DROP 01',
  color text not null default 'Black',
  image_url text not null,
  description text not null default '',
  sizes text[] not null default array['S','M','L','XL'],
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  customer_name text not null,
  phone text not null,
  email text,
  address text not null,
  city text not null,
  postal_code text,
  payment_method text not null default 'COD' check (payment_method = 'COD'),
  items jsonb not null,
  total integer not null check (total >= 0),
  status text not null default 'New' check (status in ('New','Confirmed','Packed','Shipped','Delivered','Cancelled')),
  created_at timestamptz not null default now()
);

create or replace function public.is_novara_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.admin_users where user_id = auth.uid()); $$;

alter table public.products enable row level security;
alter table public.admin_users enable row level security;
alter table public.orders enable row level security;

drop policy if exists "Anyone can view active products" on public.products;
create policy "Anyone can view active products" on public.products for select using (active = true or public.is_novara_admin());
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products for all to authenticated using (public.is_novara_admin()) with check (public.is_novara_admin());

drop policy if exists "Admins view admin list" on public.admin_users;
create policy "Admins view admin list" on public.admin_users for select to authenticated using (public.is_novara_admin());

drop policy if exists "Customers submit COD orders" on public.orders;
create policy "Customers submit COD orders" on public.orders for insert to anon, authenticated with check (payment_method = 'COD');
drop policy if exists "Admins view and update orders" on public.orders;
create policy "Admins view and update orders" on public.orders for all to authenticated using (public.is_novara_admin()) with check (public.is_novara_admin());

